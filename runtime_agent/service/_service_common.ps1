# Shared helpers for OpenAS2 Runtime Agent Windows Service scripts.

$script:ServiceId = "OpenAS2RuntimeAgent"
$script:ServiceDisplayName = "OpenAS2 Runtime Agent"
$script:DefaultDeployRoot = "C:\OpenAS2\agent"
$script:DefaultOpenAs2Root = "C:\OpenAS2"
$script:WinSWReleaseUrl = "https://github.com/winsw/winsw/releases/download/v2.12.0/WinSW-x64.exe"

function Test-Administrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Assert-Administrator {
    if (-not (Test-Administrator)) {
        throw "This script must run from an elevated PowerShell (Run as administrator)."
    }
}

function Get-ServiceDeployPaths {
    param([string]$DeployRoot = $script:DefaultDeployRoot)
    $serviceDir = Join-Path $DeployRoot "service"
    [pscustomobject]@{
        DeployRoot   = $DeployRoot
        ServiceDir   = $serviceDir
        EnvFile      = Join-Path $DeployRoot "agent.env"
        AgentScript  = Join-Path $DeployRoot "agent.py"
        StartAgentPs1 = Join-Path $DeployRoot "start_agent.ps1"
        RunnerPs1    = Join-Path $serviceDir "run_agent_for_service.ps1"
        XmlPath      = Join-Path $serviceDir "$($script:ServiceId).xml"
        ExePath      = Join-Path $serviceDir "$($script:ServiceId).exe"
        LogDir       = Join-Path $DeployRoot "logs"
    }
}

function Resolve-PythonExe {
    param([string]$Preferred = $env:OPENAS2_PYTHON)
    if ($Preferred -and (Test-Path -LiteralPath $Preferred)) {
        return (Resolve-Path -LiteralPath $Preferred).Path
    }
    $cmd = Get-Command python -ErrorAction SilentlyContinue
    if (-not $cmd) { $cmd = Get-Command py -ErrorAction SilentlyContinue }
    if (-not $cmd) {
        throw "Python not found on PATH. Install Python or pass -PythonExe."
    }
    return $cmd.Source
}

function Write-AgentEnvFile {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Token,
        [string]$OpenAs2Root = $script:DefaultOpenAs2Root,
        [string]$PythonExe = "",
        [string]$HostBind = "0.0.0.0",
        [string]$Port = "9475"
    )
    $dir = Split-Path -Parent $Path
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    $lines = @(
        "# Generated by Install-RuntimeAgentService.ps1 — do not commit this file.",
        "# Contains the Runtime Agent bearer token.",
        "OPENAS2_AGENT_TOKEN=$Token",
        "OPENAS2_ROOT=$OpenAs2Root",
        "OPENAS2_AGENT_HOST=$HostBind",
        "OPENAS2_AGENT_PORT=$Port"
    )
    if ($PythonExe) {
        $lines += "OPENAS2_PYTHON=$PythonExe"
    }
    # UTF-8 without BOM for simple KEY=VALUE parsing
    [System.IO.File]::WriteAllLines($Path, $lines)
}

function Ensure-WinSW {
    param(
        [Parameter(Mandatory = $true)][string]$ExePath,
        [string]$Url = $script:WinSWReleaseUrl
    )
    $dir = Split-Path -Parent $ExePath
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    if (Test-Path -LiteralPath $ExePath) {
        return
    }
    Write-Host "Downloading WinSW from $Url ..."
    $tmp = Join-Path $env:TEMP ("WinSW-x64-{0}.exe" -f [guid]::NewGuid().ToString("n"))
    try {
        Invoke-WebRequest -Uri $Url -OutFile $tmp -UseBasicParsing
        Copy-Item -LiteralPath $tmp -Destination $ExePath -Force
    } finally {
        Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    }
    if (-not (Test-Path -LiteralPath $ExePath)) {
        throw "Failed to install WinSW at $ExePath"
    }
}
